// Builds build/dev: a copy of src/ plus the dev menu (dev/DevMenu.js) and
// DevData.js, generated with the examples and your script ID.
// Push it with `npm run push:dev`; a normal `npm run push` removes it again.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'build', 'dev');
const project = JSON.parse(fs.readFileSync(path.join(root, '.clasp.json'), 'utf8'));

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'src'), path.join(out, 'src'), { recursive: true });
fs.copyFileSync(path.join(root, 'dev', 'DevMenu.js'), path.join(out, 'src', 'DevMenu.js'));
fs.writeFileSync(path.join(out, '.clasp.json'), JSON.stringify({ scriptId: project.scriptId, rootDir: 'src' }, null, 2));

const examples = {};
for (const file of fs.readdirSync(path.join(root, 'examples')).filter(f => f.endsWith('.json')).sort()) {
  examples['Example ' + file.replace(/\.json$/, '')] = JSON.parse(fs.readFileSync(path.join(root, 'examples', file), 'utf8'));
}

fs.writeFileSync(path.join(out, 'src', 'DevData.js'), `// Generated by scripts/build-dev.js. Not part of the normal build.
var DEV_EXAMPLES = ${JSON.stringify(examples)};
var DEV_SCRIPT_ID = ${JSON.stringify(project.scriptId)};
`);

console.log('Built the dev menu with ' + Object.keys(examples).length + ' examples into ' + path.relative(root, out));
